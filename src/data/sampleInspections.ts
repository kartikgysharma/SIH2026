// Helper to create an SVG data URL for crisp, dependable label rendering
function createLabelSvg(title: string, brand: string, items: { text: string; sub?: string }[], bgColor = '#ffffff', accentColor = '#0B2545'): string {
  const svg = `
  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 800" width="600" height="800">
    <rect width="600" height="800" fill="${bgColor}" rx="8"/>
    <rect x="16" y="16" width="568" height="768" fill="none" stroke="#e2e8f0" stroke-width="2" rx="6"/>
    
    <!-- Top Brand Header Banner -->
    <rect x="16" y="16" width="568" height="90" fill="${accentColor}" rx="6 6 0 0"/>
    <text x="40" y="55" font-family="-apple-system, BlinkMacSystemFont, sans-serif" font-size="28" font-weight="bold" fill="#ffffff">${brand}</text>
    <text x="40" y="85" font-family="-apple-system, BlinkMacSystemFont, sans-serif" font-size="14" fill="#94a3b8">${title}</text>
    
    <!-- Product Graphic Mock -->
    <rect x="40" y="125" width="520" height="150" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1" rx="4"/>
    <circle cx="300" cy="190" r="45" fill="#e2e8f0"/>
    <text x="300" y="195" font-family="sans-serif" font-size="14" font-weight="600" fill="#64748b" text-anchor="middle">PACKAGED COMMODITY LABEL</text>
    <text x="300" y="215" font-family="sans-serif" font-size="11" fill="#94a3b8" text-anchor="middle">Legal Metrology &amp; FSSAI Declaration Panel</text>

    <!-- Statutory Declarations Panel -->
    <rect x="40" y="295" width="520" height="460" fill="#ffffff" stroke="#94a3b8" stroke-width="1.5" rx="4"/>
    <rect x="40" y="295" width="520" height="30" fill="#f1f5f9" rx="4 4 0 0"/>
    <text x="55" y="315" font-family="monospace" font-size="12" font-weight="bold" fill="#334155">MANDATORY STATUTORY DECLARATIONS (LMPC 2011)</text>
    
    <!-- Items list -->
    ${items
      .map((item, index) => {
        const y = 350 + index * 48;
        return `
          <g>
            <text x="55" y="${y}" font-family="sans-serif" font-size="13" font-weight="bold" fill="#0f172a">${item.text}</text>
            ${item.sub ? `<text x="55" y="${y + 18}" font-family="monospace" font-size="11" fill="#64748b">${item.sub}</text>` : ''}
            <line x1="55" y1="${y + 26}" x2="545" y2="${y + 26}" stroke="#f1f5f9" stroke-width="1"/>
          </g>
        `;
      })
      .join('')}

    <!-- Footer Bar -->
    <rect x="40" y="715" width="520" height="40" fill="#f8fafc" rx="0 0 4 4"/>
    <text x="55" y="738" font-family="monospace" font-size="10" fill="#64748b">REVISED STANDARD UNIT SALE PRICE &amp; NET QUANTITY NOTIFICATION COMPLIANT</text>
  </svg>
  `;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

